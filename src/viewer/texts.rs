#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_languages_cover_all_tabs() {
        let ru = UiTexts::of(Lang::Ru);
        let en = UiTexts::of(Lang::En);
        for (a, b) in [
            (ru.tab_memory, en.tab_memory),
            (ru.tab_graph, en.tab_graph),
            (ru.tab_sessions, en.tab_sessions),
            (ru.tab_lifecycle, en.tab_lifecycle),
            (ru.tab_stats, en.tab_stats),
            (ru.tab_secrets, en.tab_secrets),
        ] {
            assert_ne!(a, b);
            assert!(!a.is_empty() && !b.is_empty());
        }
        assert_ne!(ru.window_title, en.window_title);
    }
}